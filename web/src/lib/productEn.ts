export function enFor(slug: string) {
  return productEn[slug];
}

export function copyFor(product: {
  slug: string;
  name: string;
  nameEn?: string | null;
  description: string;
  benefits: string;
  usage: string;
  takenWith?: string | null;
  unaniNote?: string | null;
}) {
  const en = productEn[product.slug];
  return {
    title: en?.title || product.nameEn || product.name,
    description: en?.description || product.description,
    benefits: en?.benefits || product.benefits,
    usage: en?.usage || product.usage,
    takenWith: product.takenWith
      ? product.takenWith
          .replace(/قہوہ/g, "Herbal tea")
          .replace(/زیرہ سفید/g, "white cumin")
          .replace(/سونف/g, "fennel")
          .replace(/ملٹھی/g, "licorice")
          .replace(/تازہ پانی/g, "fresh water")
          .replace(/عرقِ شوگر نل/g, "Arq-e-Shugarnil")
          .replace(/چمچ/g, "spoons")
          .replace(/پانی میں ملا کر/g, "mixed in water")
          .replace(/سبز الائچی/g, "green cardamom")
          .replace(/الائچی سبز/g, "green cardamom")
          .replace(/اجوائن دیسی/g, "desi ajwain")
          .replace(/پودینہ/g, "mint")
          .replace(/دہی کی لسی/g, "yogurt lassi")
      : "",
    temperament: product.unaniNote || "",
  };
}

export function formEn(text: string) {
  return text
    .replace(/ٹیبلٹ/g, "tablets")
    .replace(/کیپسول/g, "capsules")
    .replace(/سفوف/g, "powder")
    .replace(/چمچ/g, "spoon")
    .replace(/گرام/g, "g");
}
